"""Write ref/lxtokens.h (the token ids of spec.py) for the C trace harness."""

from pathlib import Path

from lx import spec as S


def header() -> str:
    lines = ["// generated by lx/cgen.py from lx/spec.py; do not edit", "#pragma once"]
    for nm, (base, size) in S.FAMILIES.items():
        lines.append(f"#define T_{nm}(p) ({base}u + (uint32_t)(p))")
        lines.append(f"#define N_{nm} {size}u")
    for nm, t in S.CONTROLS.items():
        lines.append(f"#define T_{nm} {t}u")
    lines.append(f"#define LX_VOCAB {S.VOCAB}u")
    lines.append(f"#define LX_N_MAX {S.N_MAX}u")
    lines.append(f"#define LX_TRAP_INT {S.TRAP_INT}u")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    out = Path(__file__).resolve().parents[2] / "ref" / "lxtokens.h"
    out.write_text(header())
    print(out)
