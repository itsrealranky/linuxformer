"""Every headline number, read from the results files (what README.md quotes).

    python tools/summary.py [--out results/summary.md]
"""

import argparse
import json
import re
from pathlib import Path

RES = Path(__file__).resolve().parents[1] / "results"


def load(name: str) -> dict:
    return json.loads((RES / name).read_text())


def runs(d: dict, what: str) -> list:
    return [r for r in d["runs"] if r["what"] == what]


def last_line(name: str, pattern: str) -> str:
    lines = [ln for ln in (RES / name).read_text().splitlines() if re.search(pattern, ln)]
    return lines[-1].strip() if lines else "(missing)"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(RES / "summary.md"))
    a = ap.parse_args()
    boot = load("m4_boot.json")
    mb = load("m4_boot_merged.json")
    mboot = runs(mb, "boot")[0]
    snap = load("m4_snapshot_compare.json")
    ram = load("m3_ramtest.json")
    mc = load("m6_merge_check.json")
    shell = load("m5_shell_merged.json")
    pure = runs(load("m5_pure_merged.json"), "pure")[0]
    chat = load("m6_chat.json")
    mmlu = load("m7_mmlu_floor_all.json")
    t = mc["text"]

    L = []
    w = L.append
    w("# Results summary (generated by tools/summary.py from lx/results)\n")
    w("## The machine and the model\n")
    w(f"- circuit: {mc['circuit']['layers']} layers, {mc['circuit']['dims']} residual dims, "
      f"{mc['circuit']['heads']} GDN heads, {mc['circuit']['ffn_units']} SwiGLU units, "
      f"no training")
    w(f"- RAM {ram['ram_bytes']:,} bytes, kernel text (ROM) {ram['rom_bytes']:,} bytes, "
      f"both in Gated DeltaNet state")
    w(f"- merged model: {mc['chip_layers']} chip layers + {mc['qwen_layers']} Qwen3.5-4B layers, "
      f"hidden {mc['hidden']}, {mc['params_B']}B parameters; chip-only model: hidden "
      f"{boot['hidden']}, {boot['params_B']}B\n")
    w("## CPU tests\n")
    w(f"- riscv-tests (76 programs x 2 ROM layouts), circuit simulator: "
      f"{last_line('ir_rvtests.log', r'^ok ')} (unsupported: the misaligned-access tests, "
      f"zicntr, and rv32mi-illegal with a ROM)")
    w(f"- riscv-tests, GPU (bf16 prefill + decode): {last_line('hf_rvtests.log', r'all ok|MISMATCH')}")
    w(f"- UART input schedules, GPU: {last_line('hf_uart.log', r'all ok|MISMATCH')}")
    pure_uart = [ln for ln in (RES / "session_uart.log").read_text().splitlines() if "pure " in ln]
    w(f"- UART input schedules, lx.session (verify in pieces, save/load, pure path): "
      f"{sum('pure ok' in ln and 'verify ok' in ln for ln in pure_uart)}/{len(pure_uart)} ok "
      f"({last_line('session_uart.log', r'all ok|FAILED')})")
    w(f"- RAM test (every word above the ROM), GPU: {ram['wrong_tokens']} wrong of "
      f"{ram['positions_checked']:,} positions in {ram['seconds']} s\n")
    w("## Boot to shell (speculative: the reference proposes, the model verifies every token)\n")
    ref = dict(zip(*[iter(last_line("m1_reference_boot.log", r"^records").split())] * 2))
    w(f"- reference (ref/lxtrace on kernel/Image, reset to the first prompt): "
      f"{int(ref['instructions']):,} instructions, {int(ref['interrupts'])} interrupts, "
      f"{int(ref['records']):,} records, {int(ref['tokens']):,} tokens + GO")
    w(f"- the proposer (lx/ref.py) against ref/lxtrace (the unmodified mini-rv32ima.h core): "
      f"riscv-tests {last_line('ref_vs_c.log', r'^same .*unsupported')}; whole boot: "
      f"{last_line('ref_vs_c.log', r'uart bytes')}")
    w(f"- trace verified: {boot['records']:,} records, {boot['tokens']:,} tokens")
    w(f"- chip-only model: {boot['wrong_tokens']} wrong of {boot['positions_checked']:,} in "
      f"{boot['seconds']} s ({boot['tok_per_s']:,} tok/s, peak {boot['peak_gb']} GB, chunk "
      f"{boot['chunk']}); console matches the reference: {boot['console_matches_reference']}")
    w(f"- merged model: 0 wrong of {mboot['tokens'] - 1:,} (lx.linux stops at the first wrong "
      f"prediction) in {mboot['seconds']} s "
      f"({mboot['tok_per_s']:,} tok/s, chunk 32768); console matches the reference: "
      f"{snap['console_matches_reference']} ({snap['console_bytes']:,} bytes)")
    w(f"- two merged boots (chunk 65536 and 32768): {snap['elements_differ']} of "
      f"{snap['elements']:,} state elements differ\n")
    w("## The shell (merged model, from the booted snapshot)\n")
    w("| command | tokens | seconds | output |")
    w("|---|---:|---:|---|")
    for r in runs(shell, "boot (snapshot)"):
        w(f"| (load snapshot) | {r['tokens']:,} | {r['seconds']} | |")
    for r in runs(shell, "run"):
        out = r["output"].strip().replace("\n", " / ").replace("|", "\\|")
        w(f"| `{r['cmd']}` | {r['tokens']:,} | {r['seconds']} | {out} |")
    w(f"\nPure path (the model alone, its argmax fed back): `{pure['cmd']}`, {pure['tokens']:,} "
      f"tokens in {pure['seconds']} s ({pure['tok_per_s']} tok/s); identical to the reference: "
      f"{pure['same_as_reference']}\n")
    w("## Qwen's text behavior (merged model's text view vs stock Qwen3.5-4B)\n")
    w(f"- Qwen tensors not bit-identical: {len(mc['qwen_tensors_not_identical'])}")
    w(f"- chip head: {len(mc['head_wrong_tokens'])} wrong of {mc['head_tokens_checked']:,} chip tokens")
    w(f"- {t['prompts']} prompts: mean KL {t['mean_kl']:.2e} (noise floor, sdpa vs eager: "
      f"{t['noise_floor_mean_kl']:.2e}), top-1 agreement {t['top1_agree']:.2%}, greedy "
      f"continuations identical {t['greedy_identical']}/{t['prompts']}")
    w(f"- MMLU ({mmlu['questions']:,} questions, zero-shot): stock {mmlu['accuracy_stock']:.2%}, "
      f"merged {mmlu['accuracy_merged']:.2%}, same answer as stock {mmlu['answers_agree']:.2%}, "
      f"mean KL {mmlu['mean_kl_last_position']:.2e}")
    w(f"- noise floor, stock with eager attention instead of sdpa (on "
      f"{mmlu['noise_floor_questions']:,} questions): accuracy {mmlu['accuracy_stock_eager']:.2%}, "
      f"same answer as stock {mmlu['eager_answers_agree']:.2%}, mean KL "
      f"{mmlu['noise_floor_kl_sdpa_vs_eager']:.2e} (merged on the same questions: "
      f"{mmlu['mean_kl_merged_on_floor_questions']:.2e})\n")
    w("## Qwen using the shell (tool calls into the machine)\n")
    for c in chat["chats"]:
        w(f"- Q: {c['question']}")
        for e in c["events"]:
            if "command" in e:
                w(f"  - shell `{e['command']}` -> `{e['response'].strip()}` "
                  f"({e['machine_tokens']:,} machine tokens, {e['machine_seconds']} s, "
                  f"{e['wrong']} wrong)")
            else:
                w(f"  - Qwen: {e['qwen']}")
    fib = load("m7_chat_fib.json")
    w("\n## Qwen writes and runs a script (merged model, one session, results/m7_chat_fib.json)\n")
    for c in fib["chats"]:
        w(f"- Q: {c['question']}")
        toks = secs = wrong = 0
        for e in c["events"]:
            if "command" in e:
                cmd, out = e["command"].splitlines(), e["response"].strip().splitlines()
                w(f"  - shell, {len(cmd)} lines from `{cmd[0]}` -> {len(out)} lines, first "
                  f"`{out[0]}`, last `{out[-1]}` ({e['machine_tokens']:,} machine tokens, "
                  f"{e['machine_seconds']} s, {e['wrong']} wrong)")
                toks, secs = toks + e["machine_tokens"], secs + e["machine_seconds"]
                wrong += e["wrong"]
            else:
                w(f"  - Qwen: {e['qwen']}")
        w(f"  - machine total: {toks:,} tokens verified in {secs:.1f} s, {wrong} wrong; peak "
          f"{fib['peak_gb']} GB")
    ex, ee = load("m8_export.json"), load("m8_export_echo.json")
    run = next(r for r in ee["runs"] if r["what"] == "run")
    snap = next(r for r in ee["runs"] if r["what"] != "run")
    w("\n## The exported checkpoint (tools/export_hf.py)\n")
    w(f"- {len(ex['shards'])} safetensors shards, {ex['weights_bytes']:,} bytes "
      f"({ex['weights_GB']} GB), {ex['tensors']} tensors ({ex['dtypes']}); booted snapshot "
      f"{ex['snapshot_bytes']:,} bytes (safetensors, no pickle)")
    w(f"- reloaded (lx.merge.load) against a fresh build: tensors differing "
      f"{len(ex['tensors_differ'])}, config keys differing {len(ex['config_keys_differ'])}, "
      f"snapshot fields differing {len(ex['snapshot_fields_differ'])}")
    w(f"- from the exported files alone: model ready in {ee['build_s']} s, snapshot in "
      f"{snap['seconds']} s, then `{run['cmd']}` {run['tokens']:,} tokens verified in "
      f"{run['seconds']} s ({run['tok_per_s']:,} tok/s), output `{run['output'].strip()}`")
    fb = load("fast_boot.json")
    fboot = runs(fb, "boot")[0]
    w("\n## lx.fast: the same weights, skipping their zeros (merged model, one H100)\n")
    w("lx/fast.py runs the chip layers over the same published tensors, on only their nonzero "
      "rows, columns and active GDN heads. Verifying (prefill) uses the stock kernels (fla's "
      "chunked kernel, cuBLAS) and torch ops; decoding uses fla's recurrent kernel, with the "
      "steps between its calls compiled by torch.compile, rounding where eager rounds. Nothing "
      "about the CPU is written by hand. The stock numbers above stand; these are the same runs "
      "with lx.fast.\n")
    w(f"- verify path (chunked prefill), boot from reset: 0 wrong of {fboot['tokens'] - 1:,} in "
      f"{fboot['seconds']} s ({fboot['tok_per_s']:,} tok/s, stock {mboot['tok_per_s']:,}: "
      f"{fboot['tok_per_s'] / mboot['tok_per_s']:.1f}x; peak {fb['peak_gb']} GB)")
    for name in ("fast_boot_compare.json", "fast_boot_compare2.json"):
        c = load(name)
        con = f", console matches the reference {c['console_matches_reference']} " \
            f"({c['console_bytes']:,} bytes)" if "console_bytes" in c else ""
        w(f"- its final state against the stock boot `{Path(c['b']).name}`: {c['elements_differ']} "
          f"of {c['elements']:,} state elements differ, host state same {c['host_state_same']}, "
          f"reference RAM same {c['reference_ram_same']}{con}")
    if (RES / "fast_decode.json").exists():
        fd = load("fast_decode.json")
        w(f"- pure path (one token at a time, the model's argmax fed back), from the booted "
          f"snapshot, `{fd['cmd']}` typed: the stock decode and lx.fast for "
          f"{fd['stock_tokens']:,} tokens, streams identical {fd['streams_identical_first_n']}, "
          f"state elements differing after them {fd['state_elements_differ_after_n']}; lx.fast "
          f"for {fd['fast_tokens']:,} tokens identical to the reference "
          f"{fd['fast_same_as_reference']}; {fd['fast_steady_tok_per_s']} tok/s (the stock "
          f"decode over the 182k-token `{pure['cmd']}` run: {pure['tok_per_s']} tok/s, "
          f"{fd['fast_steady_tok_per_s'] / pure['tok_per_s']:.1f}x)")
    if (RES / "pure_boot.json").exists():
        pb = load("pure_boot.json")
        w(f"- pure boot, from reset to the shell prompt, the model alone (no reference, no "
          f"prefill; the proposer's stream only compared with afterwards, chunk by chunk): "
          f"{pb['tokens']:,} tokens of {pb['reference_tokens']:,}, identical to the reference "
          f"{pb['same_as_reference']} (first difference: {pb['first_difference']}), in "
          f"{pb['seconds']} s = {pb['seconds'] / 3600:.2f} h ({pb['tok_per_s']} tok/s, peak "
          f"{pb['peak_gb']} GB); console matches the reference {pb['console_matches_reference']} "
          f"({pb['console_bytes']:,} bytes)")
        if (RES / "pure_boot_compare.json").exists():
            c = load("pure_boot_compare.json")
            w(f"- the pure boot's final state against the stock (prefill) boot: "
              f"{c['elements_differ']:,} of {c['elements']:,} state elements differ, host state "
              f"same {c['host_state_same']}, reference RAM same {c['reference_ram_same']}")
            for d in c.get("differences", []):
                w(f"  - layer {d['layer']} {d['state']} state {d['index']}: pure {d['a']:,.0f}, "
                  f"prefill {d['b']:,.0f}")
            if c.get("differences"):
                w("  - these are a state row's ballast columns, which the circuit sets to "
                  "2^24 = 16,777,216 (lx/ir.py A_REF): the decode kernel's sum lands on it, the "
                  "chunked prefill kernel's one fp32 step below; the predictions are the same")
    if (RES / "fast_boot_compiled.json").exists():
        fc = load("fast_boot_compiled.json")
        cb = runs(fc, "boot")[0]
        w(f"- verify path with the causal conv and silu compiled as well (fp32 products in the "
          f"stock kernel's tap order, rounded once), boot from reset: 0 wrong of "
          f"{cb['tokens'] - 1:,} in {cb['seconds']} s ({cb['tok_per_s']:,} tok/s: "
          f"{cb['tok_per_s'] / mboot['tok_per_s']:.1f}x stock; peak {fc['peak_gb']} GB)")
        if (RES / "fast_compare_compiled.json").exists():
            c = load("fast_compare_compiled.json")
            w(f"- its final state against the stock boot: {c['elements_differ']} of "
              f"{c['elements']:,} state elements differ, host state same "
              f"{c['host_state_same']}, reference RAM same {c['reference_ram_same']}")
    if (RES / "lean_boot.json").exists():
        lb = load("lean_boot.json")
        lr = runs(lb, "boot")[0]
        w("\n## A 22 GiB GPU budget: lx.fast with the chip projections in host memory\n")
        w("The chip layers' projections (16.15 GB of bf16, 0.08% nonzero) stay in host memory; "
          "lx.fast holds their nonzero parts on the GPU, beside Qwen's 32 layers and the "
          "embedding (15.8 GB). Measured on the H100 with PyTorch's allocator capped at "
          f"{lb['max_gib']} GiB, not on a 24 GB card (whose speed will differ).\n")
        w(f"- boot from reset (chunk {lb['chunk']}): 0 wrong of {lr['tokens'] - 1:,} in "
          f"{lr['seconds']} s ({lr['tok_per_s']:,} tok/s); peak allocated {lb['peak_gb']} GB, "
          f"reserved {lb['peak_reserved_gb']} GB")
        if (RES / "lean_compare.json").exists():
            c = load("lean_compare.json")
            w(f"- its final state against the stock boot: {c['elements_differ']} of "
              f"{c['elements']:,} state elements differ, host state same "
              f"{c['host_state_same']}, reference RAM same {c['reference_ram_same']}")
        if (RES / "lean_chat.json").exists():
            lc = load("lean_chat.json")
            for c in lc["chats"]:
                sh = [e for e in c["events"] if "command" in e]
                ans = [e["qwen"] for e in c["events"] if "qwen" in e]
                w(f"- Qwen using the shell, same cap: {len(sh)} command(s), "
                  f"{sum(e['wrong'] for e in sh)} wrong machine tokens; answer: "
                  f"{ans[-1] if ans else '(none)'}")
            w(f"- peak allocated {lc['peak_gb']} GB, reserved {lc['peak_reserved_gb']} GB")
    text = "\n".join(L) + "\n"
    Path(a.out).write_text(text)
    print(text)


if __name__ == "__main__":
    main()
